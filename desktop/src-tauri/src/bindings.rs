//! Generates the TypeScript IPC contract. Run via `pnpm bindings`.
//!
//! Output must be deterministic: the file is prettier-ignored and verified by running
//! the exporter twice in CI.

use specta_typescript::Typescript;

const OUTPUT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/../src/lib/ipc/bindings.ts");

pub fn export() -> Result<(), Box<dyn std::error::Error>> {
    let path = std::path::Path::new(OUTPUT);
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    // i64 ids cross the wire as `number`: values are epoch millis and rowids, far below
    // 2^53, so the truncation warning does not apply here.
    crate::commands::builder()
        .dangerously_cast_bigints_to_number()
        .export(
            Typescript::default().header("// @generated by `pnpm bindings` — do not edit\n"),
            path,
        )?;
    println!("bindings written to {OUTPUT}");
    Ok(())
}
